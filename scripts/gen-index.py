#!/usr/bin/env python3
"""Regenerate docs/INDEX.md: a compact map of routes, pages, exports and models.
Run: python3 -I scripts/gen-index.py  (from KABADI-WALA/). Read INDEX.md instead of opening many files."""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "src"
out = ["# INDEX (generated by scripts/gen-index.py — do not edit)\n"]

out.append("## API routes (src/app/api)\n")
for f in sorted((src / "app" / "api").rglob("route.ts")):
    methods = re.findall(r"export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b", f.read_text())
    url = "/" + "/".join(f.relative_to(src / "app").parent.parts)
    out.append(f"- {','.join(methods) or '?'} {url}")

out.append("\n## Pages (src/app)\n")
for f in sorted((src / "app").rglob("page.tsx")):
    url = "/" + "/".join(f.relative_to(src / "app").parent.parts)
    out.append(f"- {url if url != '/.' else '/'}  ({f.relative_to(root)})")

out.append("\n## Exports (src/lib, src/components)\n")
pat = re.compile(r"^export\s+(?:async\s+)?(?:function|const|class|type|interface|enum)\s+(\w+)", re.M)
for f in sorted(list((src / "lib").rglob("*.ts*")) + list((src / "components").rglob("*.ts*"))):
    if "openapi" in f.parts:
        continue
    names = pat.findall(f.read_text())
    if names:
        out.append(f"- {f.relative_to(root)} ({len(f.read_text().splitlines())} lines): {', '.join(names)}")

out.append("\n## Prisma models (prisma/schema.prisma)\n")
schema = (root / "prisma" / "schema.prisma").read_text().splitlines()
for i, line in enumerate(schema, 1):
    m = re.match(r"^(model|enum)\s+(\w+)", line)
    if m:
        out.append(f"- {m.group(1)} {m.group(2)} (line {i})")

(root / "docs" / "INDEX.md").write_text("\n".join(out) + "\n")
print("wrote docs/INDEX.md")
